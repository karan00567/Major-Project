"""T-407 — run artefacts: review.md, refs.bib, insights.csv.

`SPEC §10`. Everything a run produces lands in ``outputs/runs/<run_id>/``
alongside ``trace.jsonl`` and the resolved ``config.yaml``, so a run is
reproducible and inspectable without re-executing it.

Each writer returns the path it wrote, and **none of them raises into the
pipeline**. A 30-minute run that completes and then dies formatting a CSV has
lost everything for no reason; a failed artefact is logged and the others still
land. Same discipline as ``TraceLogger``.
"""

from __future__ import annotations

import csv
import json
import logging
import pathlib
import re
from typing import Any

from researchgpt.core.models import Paper, PaperInsight

log = logging.getLogger(__name__)


def _safe(fn):
    """An artefact failure must never lose the run that produced it."""

    def wrapper(*args, **kwargs):
        try:
            return fn(*args, **kwargs)
        except Exception as exc:  # pragma: no cover - defensive
            log.warning("%s failed: %s: %s", fn.__name__, type(exc).__name__, exc)
            return None

    wrapper.__name__ = fn.__name__
    wrapper.__doc__ = fn.__doc__
    return wrapper


@_safe
def write_markdown(run_dir: pathlib.Path, review: str) -> pathlib.Path:
    path = run_dir / "review.md"
    path.write_text(review, encoding="utf-8")
    return path


def _bibtex_key(paper: Paper, used: set[str]) -> str:
    first = (paper.authors[0].split()[-1] if paper.authors else "anon").lower()
    first = re.sub(r"[^a-z]", "", first) or "anon"
    word = ""
    for token in re.findall(r"[A-Za-z]{4,}", paper.title or ""):
        if token.lower() not in {"with", "from", "that", "this", "using", "toward"}:
            word = token.lower()
            break
    base = f"{first}{paper.year or ''}{word}"
    key, n = base, 1
    while key in used:
        n += 1
        key = f"{base}{n}"
    used.add(key)
    return key


@_safe
def write_bibtex(run_dir: pathlib.Path, papers: list[Paper]) -> pathlib.Path:
    """One entry per cited paper.

    ``@misc`` when there is no venue: claiming ``@article`` for something we
    only know the title of would be a small fabrication in a project whose
    subject is citation accuracy.
    """
    path = run_dir / "refs.bib"
    used: set[str] = set()
    out = ["% Generated by ResearchGPT (T-407). Verify before submission (T-813).", ""]
    for paper in papers:
        key = _bibtex_key(paper, used)
        kind = "article" if paper.venue else "misc"
        fields = [f"  title  = {{{paper.title or 'Untitled'}}}"]
        if paper.authors:
            fields.append("  author = {" + " and ".join(paper.authors) + "}")
        if paper.year:
            fields.append(f"  year   = {{{paper.year}}}")
        if paper.venue:
            fields.append(f"  journal= {{{paper.venue}}}")
        if paper.doi:
            fields.append(f"  doi    = {{{paper.doi}}}")
        if paper.url:
            fields.append(f"  url    = {{{paper.url}}}")
        out.append(f"@{kind}{{{key},\n" + ",\n".join(fields) + "\n}\n")
    path.write_text("\n".join(out), encoding="utf-8")
    return path


@_safe
def write_insight_table(
    run_dir: pathlib.Path, papers: list[Paper], insights: list[PaperInsight]
) -> pathlib.Path:
    """The four-field comparison table — the answer to SurveyGen's "limited
    critical analysis". This CSV is a graded artefact in its own right."""
    path = run_dir / "insights.csv"
    by_id = {p.paper_id: p for p in papers}
    columns = ["paper_id", "title", "year", "venue", "doi", "text_availability",
               "methodology", "advantages", "disadvantages", "critique",
               "datasets", "metrics", "results", "limitations", "extraction_note"]
    with path.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=columns)
        writer.writeheader()
        for insight in insights:
            paper = by_id.get(insight.paper_id)
            writer.writerow({
                "paper_id": insight.paper_id,
                "title": (paper.title if paper else "") or "",
                "year": (paper.year if paper else "") or "",
                "venue": (paper.venue if paper else "") or "",
                "doi": (paper.doi if paper else "") or "",
                "text_availability": paper.text_availability if paper else "",
                "methodology": insight.methodology or "",
                "advantages": insight.advantages or "",
                "disadvantages": insight.disadvantages or "",
                "critique": insight.critique or "",
                "datasets": "; ".join(insight.datasets),
                "metrics": "; ".join(insight.metrics),
                "results": insight.results or "",
                "limitations": insight.limitations or "",
                "extraction_note": insight.extraction_note or "",
            })
    return path


@_safe
def write_corpus(
    run_dir: pathlib.Path, papers: list[Paper], extracted_ids: list[str],
    retrieval_log: list[dict[str, Any]] | None = None,
) -> pathlib.Path:
    """Persist the retrieved corpus, so a run can be SCORED without re-running it.

    Added after the first flagship attempt: T-409 measures recall against the
    35-paper answer key, and the *union* recall (did retrieval find it at all?)
    needs every retrieved paper, not just the ``max_papers`` that reached the
    Extractor. Without this the only way to score a run is to re-retrieve, which
    costs an hour and burns OpenAlex budget that is now metered (0.2).

    ``extracted_ids`` records which of them actually reached the Extractor, so
    union recall and corpus recall can be separated (`decisions.txt` D-04).
    """
    path = run_dir / "corpus.json"
    path.write_text(json.dumps({
        "papers": [p.model_dump() for p in papers],
        "extracted_paper_ids": list(extracted_ids),
        "retrieval_log": retrieval_log or [],
    }, indent=1, default=str), encoding="utf-8")
    return path


@_safe
def write_config(run_dir: pathlib.Path, cfg: Any) -> pathlib.Path:
    """The resolved config, so a run can be reproduced exactly (SPEC 14.10)."""
    path = run_dir / "config.json"
    path.write_text(json.dumps(cfg.model_dump(), indent=2, default=str), encoding="utf-8")
    return path


__all__ = ["write_markdown", "write_bibtex", "write_insight_table",
           "write_corpus", "write_config"]
